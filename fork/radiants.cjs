#!/usr/bin/env node
/* ============ fork/radiants.cjs — which radiant forms exist (MrSurvivor) ============
 *   node fork/radiants.cjs          (fork/build.cjs runs it too)
 *
 * Looks for recoloured sheets in assets/pokemon/{dex}/r/ (made from the Radiant Sprite Kit,
 * radiant-kit/index.html) and writes js/fork/radiant-list.js: the pool the radiant ritual
 * rolls from (js/fork/radiant.js), and js/fork/radiants.json, the same list the game also reads
 * at runtime (so fork/radiant-admin.cjs can publish a radiant without a rebuild).
 *   G.RADIANTS = { dex: { lab: ['SpAttack'], mega: true, rarity: 5 } }
 * rarity (1-5) is the radiant's weight in the ritual: kept from radiants.json (set in
 * fork/radiant-admin.cjs), otherwise the Pokémon's own gacha rarity.
 * A radiant counts only when it has every standard sheet the normal form has, each the same
 * size as the normal one (the game reads frame sizes from the normal sheet). Its Lab sheets
 * (r/lab/) and its Mega (m{dex}/r/) are optional: missing ones fall back to the normal look.
 * Anything wrong is printed and that form is left out; --strict makes it fail instead.
 */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const MON = path.join(ROOT, 'assets', 'pokemon');
const OUT = path.join(ROOT, 'js', 'fork', 'radiant-list.js');
const JSON_OUT = path.join(ROOT, 'js', 'fork', 'radiants.json');
const vm = require('vm');
const STRICT = process.argv.includes('--strict');

/** Width and height from a PNG's header, or null. */
function size(file) {
  try {
    const b = Buffer.alloc(24), fd = fs.openSync(file, 'r');
    fs.readSync(fd, b, 0, 24, 0); fs.closeSync(fd);
    return b.readUInt32BE(0) === 0x89504e47 ? [b.readUInt32BE(16), b.readUInt32BE(20)] : null;
  } catch (e) { return null; }
}
const pngs = dir => fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.endsWith('.png')).map(f => f.slice(0, -4)) : [];

/** Problems with the radiant in `dir` (r/) against the normal sheets in `base`. */
function check(base, dir, required) {
  const bad = [];
  for (const a of required) {
    const n = size(path.join(base, a + '.png')), r = size(path.join(dir, a + '.png'));
    if (!r) bad.push(`missing ${a}.png`);
    else if (n && (n[0] !== r[0] || n[1] !== r[1])) bad.push(`${a}.png is ${r.join('×')}, the normal one is ${n.join('×')}`);
  }
  return bad;
}

// Rarities: as set before (radiants.json), else the Pokémon's (js/data/pokedex.js).
let before = {};
try { before = JSON.parse(fs.readFileSync(JSON_OUT, 'utf8')); } catch (e) { /* first time */ }
const DEX = {};
try { const G = {}; vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js', 'data', 'pokedex.js'), 'utf8'), { G }); for (const p of G.DEX) DEX[p.dex] = p; } catch (e) { /* old checkout */ }
const rarityOf = d => { const r = before[d] && +before[d].rarity; return r >= 1 && r <= 5 ? r : (DEX[d] && DEX[d].rarity) || 1; };

const list = {}, problems = [];
for (const d of fs.readdirSync(MON).filter(d => /^\d+$/.test(d)).sort((a, b) => a - b)) {
  const dir = path.join(MON, d, 'r');
  if (!fs.existsSync(dir)) continue;
  const base = path.join(MON, d);
  const bad = check(base, dir, pngs(base));
  if (bad.length) { problems.push(`#${d}: ` + bad.join('; ')); continue; }
  const e = {};
  const lab = pngs(path.join(dir, 'lab')).filter(a => !check(path.join(base, 'lab'), path.join(dir, 'lab'), [a]).length);
  if (lab.length) e.lab = lab;
  const mb = path.join(MON, 'm' + d), md = path.join(mb, 'r');
  if (fs.existsSync(md)) {
    const mbad = check(mb, md, pngs(mb));
    if (mbad.length) problems.push(`#${d} Mega: ` + mbad.join('; ') + ' (left out; the radiant shows its normal Mega)');
    else e.mega = true;
  }
  e.rarity = rarityOf(d);
  list[d] = e;
}

const text = `/* ============ radiant-list.js — GENERATED by fork/radiants.cjs, don't edit ============
 * The radiant forms that exist (sheets in assets/pokemon/{dex}/r/): the pool the radiant
 * ritual rolls from (js/fork/radiant.js). lab: its Lab sheets in r/lab/; mega: m{dex}/r/ too;
 * rarity: its weight in the ritual. Same list as js/fork/radiants.json.
 */
G.RADIANTS = ${JSON.stringify(list)};
`;
// (Same text with Windows line endings, as git checks it out there, counts as unchanged.)
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== text) fs.writeFileSync(OUT, text);
const json = JSON.stringify(list, null, 2) + '\n';
if (!fs.existsSync(JSON_OUT) || fs.readFileSync(JSON_OUT, 'utf8').replace(/\r\n/g, '\n') !== json) fs.writeFileSync(JSON_OUT, json);
for (const p of problems) console.warn('radiants: ' + p);
console.log(`radiants: ${Object.keys(list).length} radiant form(s)` + (problems.length ? `, ${problems.length} left out` : ''));
if (STRICT && problems.length) process.exit(1);
